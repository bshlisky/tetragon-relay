//go:build testtools

package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/bshlisky/tetragon-relay/internal/testvectors"
)

func writeVectorsReadme(dir string) error {
	vectors, err := testvectors.LoadDir(dir)
	if err != nil {
		return err
	}

	var b strings.Builder
	b.WriteString("# Test vectors\n\n")
	b.WriteString("Generated by `go run -tags testtools ./cmd/bundlesign-test`. " +
		"Every vector below is checked against the real internal/trust and " +
		"internal/verify code at generation time (see cmd/bundlesign-test/vectors.go, " +
		"saveChecked); none is committed unless the actual package behavior matches " +
		"its expected_result / expected_error.\n\n")
	b.WriteString("**All keys embedded in these fixtures are freshly generated, " +
		"test-only ECDSA P-384 keys. They are not used anywhere outside this " +
		"testdata directory and must never be treated as real credentials.**\n\n")
	b.WriteString("| File | Kind | Expected | Why |\n")
	b.WriteString("| --- | --- | --- | --- |\n")
	for _, v := range vectors {
		expected := v.ExpectedResult
		if expected == "" {
			expected = v.ExpectedError
		}
		fmt.Fprintf(&b, "| `%s.json` | %s | `%s` | %s |\n", v.Name, v.Kind, expected, v.Description)
	}
	b.WriteString("\nPAE length-confusion resistance (\"PAE length mismatch\") is covered by a " +
		"dedicated unit test, `TestPAE_LengthPrefixPreventsAmbiguity` in " +
		"internal/dsse/pae_test.go, rather than a JSON fixture: it is a property of " +
		"the PAE construction itself, not of any one envelope.\n")

	return os.WriteFile(filepath.Join(dir, "README.md"), []byte(b.String()), 0o644)
}
