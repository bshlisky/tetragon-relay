// Package redactgen generates internal/telemetry/redact_gen.go: the
// field-specific redactor for every message reachable from Tetragon
// v1.8.0's GetEventsResponse (step 7b P2, replacing the reflection walk
// on the hot path).
//
// The rules are the walk's (ADR 0039 section 7), decided here once per
// field from the descriptors instead of per event:
//   - a field named environment_variables is cleared;
//   - a singular string field named arguments gets the argv rules;
//   - every other string (singular, repeated, map value) gets the
//     ~/.ssh path rule;
//   - message fields (singular, repeated, map value, oneof case) recurse;
//   - unknown fields are dropped from every message (a field this API
//     version does not know cannot be redacted, so it is not kept).
//
// Reflection is used here, at generation time only. The generated code
// uses the Go types directly. TestRedactGenUpToDate (this package)
// regenerates and compares, so a change to the vendored API that is not
// regenerated fails CI.
package redactgen

import (
	"bytes"
	"fmt"
	"go/format"
	"reflect"
	"sort"
	"strings"

	"google.golang.org/protobuf/reflect/protoreflect"

	tetragonpb "github.com/bshlisky/tetragon-relay/third_party/tetragon/v1.8.0/api/v1/tetragon"
)

// goField is one struct field of a generated message type.
type goField struct {
	name string
	typ  reflect.Type
}

type gen struct {
	buf     bytes.Buffer
	imports map[string]string // import path -> alias
	done    map[protoreflect.FullName]bool
	queue   []protoreflect.Message
}

// Generate returns the gofmt'd source of redact_gen.go.
func Generate() ([]byte, error) {
	g := &gen{imports: map[string]string{}, done: map[protoreflect.FullName]bool{}}
	root := (&tetragonpb.GetEventsResponse{}).ProtoReflect()
	g.enqueue(root)
	var body bytes.Buffer
	for len(g.queue) > 0 {
		m := g.queue[0]
		g.queue = g.queue[1:]
		g.buf.Reset()
		if err := g.message(m); err != nil {
			return nil, err
		}
		body.Write(g.buf.Bytes())
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by internal/telemetry/internal/redactgen. DO NOT EDIT.\n\n")
	out.WriteString("package telemetry\n\nimport (\n")
	paths := make([]string, 0, len(g.imports))
	for p := range g.imports {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, p := range paths {
		fmt.Fprintf(&out, "\t%s %q\n", g.imports[p], p)
	}
	out.WriteString(")\n\n")
	out.WriteString("// redactEvent redacts ev in place (see Redactor.Redact).\n")
	fmt.Fprintf(&out, "func (r *redaction) redactEvent(ev *%s) { r.%s(ev) }\n\n", g.typeName(reflect.TypeOf(root.Interface()).Elem()), funcName(root.Descriptor()))
	out.Write(body.Bytes())
	src, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("redactgen: gofmt: %w\n%s", err, out.Bytes())
	}
	return src, nil
}

func (g *gen) enqueue(m protoreflect.Message) {
	if g.done[m.Descriptor().FullName()] {
		return
	}
	g.done[m.Descriptor().FullName()] = true
	g.queue = append(g.queue, m)
}

func funcName(md protoreflect.MessageDescriptor) string {
	return "redact_" + strings.ReplaceAll(string(md.FullName()), ".", "_")
}

// typeName is t's qualified Go name in the generated file.
func (g *gen) typeName(t reflect.Type) string {
	p := t.PkgPath()
	alias, ok := g.imports[p]
	if !ok {
		alias = p[strings.LastIndex(p, "/")+1:]
		if alias == "tetragon" {
			alias = "tetragonpb"
		}
		for _, a := range g.imports {
			if a == alias {
				alias += fmt.Sprint(len(g.imports))
			}
		}
		g.imports[p] = alias
	}
	return alias + "." + t.Name()
}

// fieldsByNumber maps each proto field number to its Go struct field, for
// fields that are not part of a oneof.
func fieldsByNumber(t reflect.Type) map[int]goField {
	out := map[int]goField{}
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		tag := f.Tag.Get("protobuf")
		if tag == "" {
			continue
		}
		var num int
		_, _ = fmt.Sscanf(strings.Split(tag, ",")[1], "%d", &num)
		out[num] = goField{name: f.Name, typ: f.Type}
	}
	return out
}

// oneofField is the Go interface field holding oneof od.
func oneofField(t reflect.Type, od protoreflect.OneofDescriptor) (string, error) {
	for i := 0; i < t.NumField(); i++ {
		if t.Field(i).Tag.Get("protobuf_oneof") == string(od.Name()) {
			return t.Field(i).Name, nil
		}
	}
	return "", fmt.Errorf("redactgen: no Go field for oneof %s", od.FullName())
}

// wrapper returns oneof case fd's Go wrapper type and the name of its
// value field, found by setting the case on a fresh message.
func wrapper(m protoreflect.Message, ifield string, fd protoreflect.FieldDescriptor) (reflect.Type, goField) {
	fresh := m.New()
	fresh.Set(fd, fresh.NewField(fd))
	wt := reflect.ValueOf(fresh.Interface()).Elem().FieldByName(ifield).Elem().Type() // *Wrapper
	inner := wt.Elem().Field(0)
	return wt.Elem(), goField{name: inner.Name, typ: inner.Type}
}

func (g *gen) message(m protoreflect.Message) error {
	md := m.Descriptor()
	t := reflect.TypeOf(m.Interface()).Elem()
	byNum := fieldsByNumber(t)
	fmt.Fprintf(&g.buf, "func (r *redaction) %s(m *%s) {\n\tif m == nil {\n\t\treturn\n\t}\n\tr.dropUnknown(m)\n", funcName(md), g.typeName(t))
	fields := md.Fields()
	for i := 0; i < fields.Len(); i++ {
		fd := fields.Get(i)
		if od := fd.ContainingOneof(); od != nil && !od.IsSynthetic() {
			continue
		}
		gf, ok := byNum[int(fd.Number())]
		if !ok {
			return fmt.Errorf("redactgen: no Go field for %s", fd.FullName())
		}
		if err := g.field(m, fd, "m."+gf.name, gf.typ); err != nil {
			return err
		}
	}
	oneofs := md.Oneofs()
	for i := 0; i < oneofs.Len(); i++ {
		od := oneofs.Get(i)
		if od.IsSynthetic() {
			continue
		}
		ifield, err := oneofField(t, od)
		if err != nil {
			return err
		}
		var cases bytes.Buffer
		saved := g.buf
		for j := 0; j < od.Fields().Len(); j++ {
			fd := od.Fields().Get(j)
			wt, inner := wrapper(m, ifield, fd)
			g.buf = bytes.Buffer{}
			if err := g.field(m, fd, "x."+inner.name, inner.typ); err != nil {
				return err
			}
			if g.buf.Len() > 0 {
				fmt.Fprintf(&cases, "\tcase *%s:\n%s", g.typeName(wt), g.buf.String())
			}
		}
		g.buf = saved
		if cases.Len() > 0 {
			fmt.Fprintf(&g.buf, "\tswitch x := m.%s.(type) {\n%s\t}\n", ifield, cases.String())
		}
	}
	g.buf.WriteString("}\n\n")
	return nil
}

// field emits the statements for one field, accessed as expr of Go type typ.
func (g *gen) field(m protoreflect.Message, fd protoreflect.FieldDescriptor, expr string, typ reflect.Type) error {
	w := &g.buf
	if fd.Name() == "environment_variables" {
		fmt.Fprintf(w, "\t%s = nil\n", expr)
		return nil
	}
	switch {
	case fd.IsMap():
		switch fd.MapValue().Kind() { //nolint:exhaustive // only string and message values carry paths
		case protoreflect.StringKind:
			fmt.Fprintf(w, "\tfor k, v := range %s {\n\t\tif o := r.path(v); o != v {\n\t\t\t%s[k] = o\n\t\t}\n\t}\n", expr, expr)
		case protoreflect.MessageKind:
			g.enqueue(m.NewField(fd).Map().NewValue().Message())
			fmt.Fprintf(w, "\tfor _, v := range %s {\n\t\tr.%s(v)\n\t}\n", expr, funcName(fd.MapValue().Message()))
		}
	case fd.IsList():
		switch fd.Kind() { //nolint:exhaustive // only string and message elements carry paths
		case protoreflect.StringKind:
			fmt.Fprintf(w, "\tfor i, v := range %s {\n\t\t%s[i] = r.path(v)\n\t}\n", expr, expr)
		case protoreflect.MessageKind, protoreflect.GroupKind:
			g.enqueue(m.NewField(fd).List().NewElement().Message())
			fmt.Fprintf(w, "\tfor _, v := range %s {\n\t\tr.%s(v)\n\t}\n", expr, funcName(fd.Message()))
		}
	case fd.Kind() == protoreflect.MessageKind || fd.Kind() == protoreflect.GroupKind:
		g.enqueue(m.NewField(fd).Message())
		fmt.Fprintf(w, "\tr.%s(%s)\n", funcName(fd.Message()), expr)
	case fd.Kind() == protoreflect.StringKind:
		rule := "path"
		if fd.Name() == "arguments" {
			rule = "argv"
		}
		if typ.Kind() == reflect.Pointer {
			fmt.Fprintf(w, "\tif %s != nil {\n\t\tif o := r.%s(*%s); o != *%s {\n\t\t\t%s = &o\n\t\t}\n\t}\n", expr, rule, expr, expr, expr)
		} else {
			fmt.Fprintf(w, "\t%s = r.%s(%s)\n", expr, rule, expr)
		}
	}
	return nil
}

// Messages lists every message the generated redactor covers (for tests).
func Messages() []protoreflect.FullName {
	g := &gen{imports: map[string]string{}, done: map[protoreflect.FullName]bool{}}
	g.enqueue((&tetragonpb.GetEventsResponse{}).ProtoReflect())
	for len(g.queue) > 0 {
		m := g.queue[0]
		g.queue = g.queue[1:]
		g.buf.Reset()
		_ = g.message(m)
	}
	out := make([]protoreflect.FullName, 0, len(g.done))
	for n := range g.done {
		out = append(out, n)
	}
	sort.Slice(out, func(i, j int) bool { return out[i] < out[j] })
	return out
}
